"""그림이 무는 값의 눈금 — 의존성 0. 줄이는 손(`_shrink.py` · PIL 이 든다)과 그림 문(홈 훅
`image-gate.py` · PIL 없이 돈다)이 **같은 숫자를 여기서 읽는다.** 두 자리에 따로 적으면 상류가
눈금을 바꾼 날 한쪽만 고쳐지고, 그때 문과 손이 서로 다른 값을 말한다.

숫자의 진본은 상류 vision 문서다(2026-09-22 확인):
  · 값은 28×28 패치 수 — `⌈가로/28⌉ × ⌈세로/28⌉`. 바이트도 압축률도 아니다
  · 모델 갈래마다 천장이 있다 — 긴 변과 패치 수. 넘는 그림은 **보내기 전에 상류가 깎는다.**
    고해상 층(Claude 4.7 이후) 긴 변 2576 · 4,784 패치 — 옛 층은 1568 · 1568
  · 그래서 천장 위의 픽셀은 값이 0 이다 — 읽는 쪽이 못 보고, 어느 판으로 깎일지도 못 고른다

⚠ **`MAX_EDGE` 는 천장이 아니라 눈금이다.** 근거는 실측 하나 — 긴 변 1169 로 그린 A4 가로 지면에서
   9.5pt 본문이 읽혔다(2026-09-21). 지면에는 맞고 **UI 스크린샷에는 작을 수 있다**(3440 화면을
   1280 으로 누르면 12px 글자가 4.5px 다). 그래서 문은 이 수를 답으로 대지 않고 「수를 보고 골라라」
   로 댄다. 더 줄이려면 먼저 눈으로 보고 정한다.
"""

PATCH = 28            # 모델이 그림을 세는 눈금 — 28×28 픽셀 한 칸이 시각 토큰 하나다
MAX_EDGE = 1280       # 줄이는 손의 기본 긴 변 · 문이 「생각해 보라」를 대는 선 — 위 머리말
LONG_EDGE_CAP = 2576  # 고해상 층 천장 — 이보다 긴 변은 상류가 깎는다
TOKEN_CAP = 4784      # 같은 층의 패치 천장


def patches(size):
    """그 치수가 무는 시각 토큰 수 — `⌈가로/28⌉ × ⌈세로/28⌉`.

    상류 표와 대조했다(2026-09-22 · vision 문서의 예시) — 200² = 64 · 1000² = 1,296 ·
    1092² = 1,521 · 1920×1080 = 2,691(고해상 층 · 안 깎일 때). 넷 다 맞았다.
    ⚠ 천장은 여기가 안 든다 — 깎인 뒤의 값은 `downscaled()` 가 참일 때 이 셈보다 작다.
    """
    w, h = size
    return -(-w // PATCH) * -(-h // PATCH)


def fit(size, max_edge):
    """긴 변을 상한에 맞춘 치수 — 비율은 그대로. 이미 작으면 그대로 돌려준다."""
    w, h = size
    if max(w, h) <= max_edge:
        return (w, h)
    scale = max_edge / float(max(w, h))
    return (max(1, round(w * scale)), max(1, round(h * scale)))


def downscaled(size):
    """상류가 이 그림을 깎나 — 긴 변이나 패치 수가 천장을 넘으면 참. 그 픽셀은 값이 0 이다."""
    return max(size) > LONG_EDGE_CAP or patches(size) > TOKEN_CAP
