#!/bin/sh
# PreToolUse(Bash) — 명령에 겹역슬래시가 들면 **돌려보낸다**(#92).
#
# 윈도우에서 Bash 도구로 보낸 명령은 셸에 닿기 전에 겹역슬래시가 하나로 접힌다 — 홑따옴표 안이든
# 따옴표 친 heredoc 안이든, 셸 표준이 글자를 그대로 둬야 하는 자리에서도. 그래서 파이썬 · sed 를
# 흘려 파일을 고치는 명령이 **성공으로 끝나고 파일만 틀린다.** 교훈을 적어 둬도 명령을 짓는 순간에는
# 안 떠올라, 판단과 무관하게 걸리는 이 층에 둔다(규범 [Layer Triage]).
# 훅이 볼 수 있는 까닭 — 접히는 것은 명령이 셸로 넘어가는 순간이고, 훅은 그 전의 도구 입력을 JSON
# 으로 받는다. JSON 안에서 역슬래시 하나는 둘로 적히므로, 겹역슬래시는 넷으로 보인다.
# ⚠ **막는다(deny) — 묻지 않는다.** 겹역슬래시는 어디에 적어도 쓴 대로 안 닿아, 막아서 잃는 명령이
#   없다. 고칠 쪽은 명령을 지은 모델이라 까닭을 돌려주면 다시 짓는다. 홑역슬래시는 안 접혀 안 건다.
# ⚠ **윈도우에서만 건다.** 리눅스에서도 접히나는 안 쟀다 — 안 접히는 자리에서 막으면 헛걸림이다.
# ⚠ 재는 것은 `command` 칸 하나다 — `cwd` 같은 다른 칸은 UNC 경로로 겹역슬래시를 들 수 있다.
#   `"command":` 는 JSON 문자열 안에서는 설 수 없는 글자라(안의 따옴표는 역슬래시가 앞선다) 키로만 걸린다.
[ "${OS:-}" = Windows_NT ] || exit 0
cmd=$(sed -nE 's/.*"command" *: *"(([^"\\]|\\.)*)".*/\1/p')
case "$cmd" in
  *'\\\\'*)
    printf '%s' '{"hookSpecificOutput":{"hookEventName":"PreToolUse","permissionDecision":"deny","permissionDecisionReason":"이 PC 에서 Bash 도구로 보낸 명령은 겹역슬래시가 셸에 닿기 전에 하나로 접힌다 — 홑따옴표 · 따옴표 친 heredoc 안에서도. 그대로 돌리면 성공으로 끝나고 결과만 틀린다. 다시 짓는다: 파일 내용이나 스크립트는 Write 로 파일에 써서 돌린다 · 파이썬 안에서 역슬래시 글자가 필요하면 chr(92) · 경로는 / 로 적는다."}}'
    ;;
esac
exit 0
