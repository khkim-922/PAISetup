#!/bin/sh
# 조각 — **파워셸은 BOM 이 있어야 하고, cmd 는 없어야 한다.** 그 둘만 막는다.
#
# 왜 이것 둘인가 — 둘 다 **파일은 멀쩡히 커밋되고 남의 PC 에서만 깨진다.**
#
#   · `*.ps1` — Windows PowerShell 5.1 은 **BOM 없는 스크립트를 시스템 ANSI 코드페이지로
#     읽는다**(한국어 윈도우는 cp949). UTF-8 로 저장한 한글이 그 자리에서 깨지고, 따옴표가
#     안 닫혀 파서가 죽는다. 콘솔 코드페이지(`chcp 65001`)는 다른 자리라 고쳐도 안 낫는다.
#   · `*.cmd` — 반대다. cmd.exe 는 배치 파일을 콘솔 OEM 코드페이지로 읽으므로 **BOM 이 붙으면
#     첫 줄이 깨진다.** `@echo off` 가 명령으로 안 읽혀 창에 그대로 찍히고 그 뒤가 어긋난다.
#
# ⚠ **고쳐 주지 않고 막는다.** 커밋 훅이 스테이지한 파일을 조용히 바꾸면, 사람이 본 것과
#   커밋된 것이 달라진다. 무엇을 어떻게 고칠지 대고 물러난다.
#   (파일을 **만드는 순간** 찍는 것은 다른 층이 든다 — `.claude/hooks/utf8-bom.sh` 가
#   Write·Edit 마다 돌아 찍는다. 여기는 그것이 안 걸린 길을 막는 마지막 자리다.)
set -u

BOM="$(printf '\357\273\277')"
FAIL=0

# 담긴 판의 머리 세 바이트.
# ⚠ **작업 트리가 아니라 담긴 판을 잰다.** 커밋되는 것은 인덱스다 — BOM 없이 담아 두고
#   작업 트리에서만 붙이면(`git add -p` · 담고 나서 고친 자리) 게이트가 초록을 내고
#   **BOM 없는 판이 그대로 커밋된다.**
# ⚠ **부르는 자리는 `case` 안이다 — 거른 뒤에 읽는다.** 담긴 것을 다 읽으면 이진 파일이
#   담기는 날 셸이 「ignored null byte in input」을 파일마다 한 줄씩 뱉는다(실측). 판정은
#   안 흔들리므로 더 조용히 나쁘다 — **뜻 없는 줄이 게이트 출력에 쌓이면 사람이 그 출력을
#   안 읽게 되고, 그러면 진짜 빨강도 같이 안 읽힌다.**
head3_of() {
  git show ":$1" 2>/dev/null | head -c 3 || true
}

# 스테이지된 것만 잰다 — 손대지 않은 파일로 커밋을 막지 않는다.
# ⚠ **`core.quotePath=false` 가 있어야 비ASCII 이름이 온다.** 기본값(참)에서 git 은
#   `"docs/\355\225\234\352\270\200.md"` 꼴로 **싸서** 내고, 그러면 줄 끝이 `"` 라 확장자
#   패턴에 안 걸리고 `[ -f ]` 도 거짓이라 **한 줄도 안 말하고 빠진다.** 우리 문서는 한국어라
#   그 이름이 드물지 않다 — 실측 2026-09-11: 한 형제 저장소에 그런 이름의 `.md` 가 322개였고,
#   같은 위반을 ASCII 이름이면 막고 한글 이름이면 통과했다.
STAGED="$(git -c core.quotePath=false diff --cached --name-only --diff-filter=ACM)"
[ -n "$STAGED" ] || exit 0

# ⚠ **줄바꿈으로만 가른다.** 기본 `IFS` 로 돌리면 `my script.ps1` 이 두 조각이 되어 둘 다
#   `[ -f ]` 에서 떨어지고 **막는 것이 존재 이유인 파일 종류가 조용히 빠진다.**
oldifs=$IFS
IFS='
'
for f in $STAGED; do
  IFS=$oldifs
  case "$f" in
    *.ps1|*.psm1|*.psd1)
      if [ "$(head3_of "$f")" != "$BOM" ]; then
        printf '✖ BOM 이 없다 — 한국어 윈도우에서 한글이 깨진다:  %s\n' "$f" >&2
        # ⚠ **`echo` 로 찍지 않는다.** 역슬래시를 먹는 셸이 있어 안내가 BOM 글자 자체로
        #   찍혔다(실측) — 그대로 복사하면 안 듣는다. `printf %s` 는 안 먹는다.
        printf '%s\n' "    고치는 법:  printf '\\357\\273\\277' | cat - '$f' > t && mv t '$f'" >&2
        FAIL=1
      fi
      ;;
    *.cmd|*.bat)
      if [ "$(head3_of "$f")" = "$BOM" ]; then
        printf '✖ BOM 이 붙었다 — cmd.exe 가 첫 줄을 못 읽는다:  %s\n' "$f" >&2
        printf '%s\n' "    고치는 법:  tail -c +4 '$f' > t && mv t '$f'" >&2
        FAIL=1
      fi
      ;;
  esac
  IFS='
'
done
IFS=$oldifs

[ "$FAIL" = 0 ] || printf '  파일은 멀쩡히 커밋되고 **남의 PC 에서만** 깨지는 자리다.\n' >&2
exit "$FAIL"
